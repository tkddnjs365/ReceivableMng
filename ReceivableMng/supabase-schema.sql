create table if not exists clients (
  id bigint generated by default as identity primary key,
  name text not null,
  email text,
  created_at timestamptz not null default now()
);

create table if not exists jobs (
  id bigint generated by default as identity primary key,
  client_id bigint not null references clients(id) on delete cascade,
  date date not null,
  amount numeric not null,
  memo text
);

create table if not exists payments (
  id bigint generated by default as identity primary key,
  job_id bigint not null references jobs(id) on delete cascade,
  date date not null,
  amount numeric not null
);

-- Row Level Security 활성화 (Supabase 기본 권장)
alter table clients enable row level security;
alter table jobs enable row level security;
alter table payments enable row level security;

-- ------------------------------------------------------------
-- 이 앱은 혼자(또는 소수 인원) 쓰는 사내용 데스크탑 프로그램이라고 가정하고,
-- anon 키로 자유롭게 읽고 쓰도록 정책을 열어둡니다.
-- 여러 명이 같은 Supabase 프로젝트를 쓰거나 외부에 노출될 가능성이 있다면
-- 아래 정책 대신 Supabase Auth 로그인을 붙이고 auth.uid() 기준으로 제한하는 걸 권장합니다.
-- ------------------------------------------------------------
create policy "allow all - clients" on clients for all using (true) with check (true);
create policy "allow all - jobs" on jobs for all using (true) with check (true);
create policy "allow all - payments" on payments for all using (true) with check (true);
